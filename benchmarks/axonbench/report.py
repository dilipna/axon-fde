"""Turning stored runs into the markdown the README embeds.

`poe bench report`. Reads the newest run per arm from `benchmarks/results/`
and writes a table.

**The report never computes a number.** It reads what a stored run recorded.
That is the whole point of separating it from the runner: a report that could
recompute could disagree with the file it claims to summarise, and the number
in the README would then depend on which of the two ran last.

**It reports what is not measured as prominently as what is.** A table
showing two green claims and silently omitting the six that are blocked reads
as a system with two claims. Every claim this harness knows about appears,
with its shortfall stated, because the honest summary of the project today is
"two measured, six blocked, and here is precisely what each one needs".
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from benchmarks.axonbench.claims import CLAIMS, ClaimStatus

__all__ = ["latest_runs", "main", "render_markdown"]

PROJECT_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = PROJECT_ROOT / "benchmarks" / "results"
REPORT_PATH = PROJECT_ROOT / "docs" / "evaluation" / "results.md"

#: How a status reads in the table. `INSUFFICIENT_DATA` is spelled out rather
#: than abbreviated: the whole reason it exists is to be read.
_BADGE = {
    ClaimStatus.MEASURED: "measured",
    ClaimStatus.REFUTED: "**refuted**",
    ClaimStatus.INSUFFICIENT_DATA: "insufficient data",
    ClaimStatus.PLACEHOLDER: "not measured",
}


@dataclass(frozen=True, slots=True)
class StoredRun:
    """One result file, as read back."""

    path: Path
    payload: dict[str, Any]

    @property
    def arm(self) -> str:
        return str(self.payload.get("arm", "unknown"))

    @property
    def completed_at(self) -> str:
        return str(self.payload.get("completed_at", ""))

    @property
    def run_id(self) -> str:
        return str(self.payload.get("provenance", {}).get("run_id", "unknown"))

    @property
    def reproducible(self) -> bool:
        return bool(self.payload.get("provenance", {}).get("reproducible", False))


def latest_runs(directory: Path | None = None) -> dict[str, StoredRun]:
    """The newest run for each arm.

    Newest by the recorded ``completed_at`` rather than by file mtime. A file
    copied or checked out fresh gets a new mtime and would otherwise become
    "the latest run" without anything having been measured.
    """
    source = directory or RESULTS_DIR
    runs: dict[str, StoredRun] = {}
    for path in sorted(source.glob("*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            # A malformed result is skipped rather than fatal, but it is not
            # silent: the report says how many were unreadable.
            continue
        run = StoredRun(path=path, payload=payload)
        existing = runs.get(run.arm)
        if existing is None or run.completed_at > existing.completed_at:
            runs[run.arm] = run
    return runs


def render_markdown(runs: dict[str, StoredRun]) -> str:
    """The table, plus what is missing and why."""
    lines: list[str] = [
        "# AxonBench results",
        "",
        "Generated by `poe bench report`. **Every number here comes from a stored",
        "run** under `benchmarks/results/`; nothing on this page is recomputed at",
        "render time, and nothing is typed by hand. That is invariant I7.",
        "",
    ]

    if not runs:
        lines += [
            "No stored runs. Run `uv run poe bench` first.",
            "",
        ]
        return "\n".join(lines)

    for arm in sorted(runs):
        run = runs[arm]
        lines += [
            f"## Arm: `{arm}`",
            "",
            f"- Run: `{run.run_id}`",
            f"- Completed: {run.completed_at}",
        ]
        provenance = run.payload.get("provenance", {})
        lines += [
            f"- Code: `{provenance.get('git_sha', 'unknown')}`",
            f"- Model: `{provenance.get('model_id', 'none')}` · "
            f"prompt `{provenance.get('prompt_version', 'none')}`",
            f"- Pack: `{provenance.get('pack_version', 'unknown')}` · "
            f"config `{provenance.get('config_hash', 'unknown')}`",
            "",
        ]
        if not run.reproducible:
            lines += [
                "> **Not reproducible.** This run was measured against code that was "
                "not committed, so nobody else can reproduce the numbers below. They "
                "are recorded for the person who ran them and must not be quoted.",
                "",
            ]

        lines += [
            "| Claim | Status | Metric | Value | Cases |",
            "|---|---|---|---|---|",
        ]
        results = {r["claim_id"]: r for r in run.payload.get("results", [])}
        for claim_id in sorted(CLAIMS):
            spec = CLAIMS[claim_id]
            result = results.get(claim_id)
            if result is None:
                lines.append(
                    f"| {claim_id} | not graded | {spec.metric} | — | "
                    f"0/{spec.required_cases} {spec.case_unit} |"
                )
                continue
            status = ClaimStatus(result["status"])
            value = "—" if status is ClaimStatus.INSUFFICIENT_DATA else f"{result['value']:g}"
            lines.append(
                f"| {claim_id} | {_BADGE[status]} | {spec.metric} | {value} | "
                f"{result['cases']}/{spec.required_cases} {spec.case_unit} |"
            )
        lines.append("")

        # Companions are printed separately rather than squeezed into the
        # table, because C1's lead time without its false-alarm rate is
        # explicitly a misuse of the claim and a cramped cell invites exactly
        # that.
        for claim_id in sorted(results):
            companions = results[claim_id].get("companions") or {}
            if companions:
                lines.append(f"**{claim_id} companion metrics** — these must be quoted together:")
                lines += [f"- `{name}`: {value:g}" for name, value in sorted(companions.items())]
                lines.append("")

        blocked = [
            results[claim_id]
            for claim_id in sorted(results)
            if ClaimStatus(results[claim_id]["status"]) is ClaimStatus.INSUFFICIENT_DATA
        ]
        if blocked:
            lines += ["### What is not measured yet, and why", ""]
            lines += [f"- **{r['claim_id']}** — {r['reason']}" for r in blocked]
            lines.append("")

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    directory = Path(argv[0]) if argv else None
    runs = latest_runs(directory)
    markdown = render_markdown(runs)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(markdown + "\n", encoding="utf-8")
    print(f"Wrote {REPORT_PATH.relative_to(PROJECT_ROOT)} from {len(runs)} arm(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
